#!/usr/bin/env python3
# =============================================================================
# hil.py - on-board self-test programs and their expected output
# -----------------------------------------------------------------------------
# Purpose : The hardware-in-the-loop self-test runs programs on the board and
#           compares everything they print on the UART, byte for byte, with
#           what the golden ISS prints for the same ELF. This module holds the
#           parts shared by the regression (which first proves the comparison
#           on the RTL), tools/make_prebuilt.py and host/board_hil.py.
# Programs: rand_<seed>   model/rand_gen.py --hil: random RV32I/Zicsr stream
#                         with traps; ends by printing all registers and the
#                         2 KB data window ("HIL BEGIN" ... "HIL END").
#           rv_<test>     riscv-tests rv32ui/rv32mi with the board
#                         environment sim/riscv_tests/env_hil: each test
#                         prints "RVTEST <code>" (1 = pass, else the failing
#                         test number * 2 + 1).
#           Both write TOHOST (so a simulation stops) and then jump to address
#           0, back into the bootloader, so the host loads the next program
#           without a manual reset.
# Expected: expected_output(elf) runs the ISS from the ELF entry until TOHOST
#           and returns (UART text, instructions executed).
# =============================================================================
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, HERE)
import iss as iss_mod        # noqa: E402
import params as params_mod  # noqa: E402

RAND_COUNT = 5000            # instruction lines per random program (fits RAM with its data)
END_MARKERS = (b"HIL END\n",)
RV_MARKER = b"RVTEST "
GCC_FLAGS = ["-march=rv32i_zicsr_zifencei", "-mabi=ilp32", "-static", "-nostdlib", "-nostartfiles", "-mno-relax"]


def gcc():
    import shutil
    g = shutil.which("riscv-none-elf-gcc")
    if not g:
        raise SystemExit("riscv-none-elf-gcc not on PATH")
    return g


def build_rand(seed, out_dir, count=RAND_COUNT):
    """Generate and assemble rand_<seed>; returns the ELF path."""
    import rand_gen
    os.makedirs(out_dir, exist_ok=True)
    src = os.path.join(out_dir, "rand_%04d.S" % seed)
    with open(src, "w", newline="\n") as fh:
        fh.write(rand_gen.Gen(seed, count, False, hil=True).program())
    elf = os.path.join(out_dir, "rand_%04d.elf" % seed)
    _link(src, elf, [])
    return elf


PROBE_S = r"""
/* generated by model/hil.py - DO NOT EDIT: reports the core type, then returns to the bootloader */
    .section .text.init, "ax"
    .globl _start
_start:
    li   x1, 0x40000000          /* UART */
    li   x2, 0x4000040C          /* SYSCTRL_FEATURES: bit 3 = pipelined core */
    lw   x3, 0(x2)
    andi x3, x3, 8
    la   x4, msg_mc
    beqz x3, 1f
    la   x4, msg_pipe
1:  lbu  x5, 0(x4)
    beqz x5, 3f
2:  lw   x6, 8(x1)
    andi x6, x6, 1
    bnez x6, 2b
    sw   x5, 0(x1)
    addi x4, x4, 1
    j    1b
3:  lw   x6, 8(x1)
    andi x6, x6, 1
    bnez x6, 3b
    jalr x0, 0(x0)
    .section .rodata
msg_pipe: .asciz "CORE pipe\n"
msg_mc:   .asciz "CORE mc\n"
"""


def build_probe(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    src = os.path.join(out_dir, "probe.S")
    with open(src, "w", newline="\n") as fh:
        fh.write(PROBE_S)
    elf = os.path.join(out_dir, "probe.elf")
    _link(src, elf, [])
    return elf


def rvtest_sources():
    """(name, path) of every rv32ui and rv32mi test in the vendored riscv-tests."""
    base = os.path.join(ROOT, "sim", "riscv_tests", "upstream", "isa")
    out = []
    for suite in ("rv32ui", "rv32mi"):
        d = os.path.join(base, suite)
        for f in sorted(os.listdir(d)):
            if f.endswith(".S"):
                out.append(("%s-%s" % (suite, f[:-2]), os.path.join(d, f)))
    return out


def build_rvtest(name, src, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    elf = os.path.join(out_dir, "rv_%s.elf" % name)
    inc = [os.path.join(ROOT, "sim", "riscv_tests", "env_hil"),
           os.path.join(ROOT, "sim", "riscv_tests", "upstream", "env", "p"),
           os.path.join(ROOT, "sim", "riscv_tests", "upstream", "isa", "macros", "scalar")]
    _link(src, elf, ["-I" + i for i in inc])
    return elf


def _link(src, elf, extra):
    ld = os.path.join(ROOT, "sim", "riscv_tests", "link.ld")
    r = subprocess.run([gcc()] + GCC_FLAGS + extra + ["-T", ld, src, "-o", elf], stdout=subprocess.PIPE,
                       stderr=subprocess.STDOUT, universal_newlines=True)
    if r.returncode:
        raise RuntimeError("build of %s failed:\n%s" % (os.path.basename(src), r.stdout[-3000:]))


def expected_output(elf, max_steps=5000000):
    """UART bytes the golden ISS prints for this program, and its instruction count."""
    P = params_mod.load()
    iss = iss_mod.Iss(P)
    e = iss_mod.load_program(iss, elf)
    iss.pc = e.entry
    out = bytearray()
    iss.soc.uart.on_tx = out.append
    n, why = iss_mod.run(iss, max_steps)
    if why != "tohost":
        raise RuntimeError("%s: ISS stopped with %s after %d steps" % (os.path.basename(elf), why, n))
    return bytes(out), n


def env_matches_upstream():
    """The env_hil RVTEST_CODE_BEGIN must equal upstream's except for write_tohost."""
    import re
    up = open(os.path.join(ROOT, "sim", "riscv_tests", "upstream", "env", "p", "riscv_test.h")).read()
    hil = open(os.path.join(ROOT, "sim", "riscv_tests", "env_hil", "riscv_test.h")).read()

    def macro(t):
        i = t.index("#define RVTEST_CODE_BEGIN")
        j = t.find("//-----", i)
        body = t[i:j if j > 0 else len(t)]
        body = re.sub(r"write_tohost:.*?reset_vector:", "write_tohost: reset_vector:", body, flags=re.S)
        return re.sub(r"\s+", " ", body).strip()
    return macro(up) == macro(hil)


def complete(buf):
    """True once a program's output is finished (its end marker has arrived)."""
    if any(m in buf for m in END_MARKERS):
        return True
    i = buf.find(RV_MARKER)
    return i >= 0 and buf.find(b"\n", i) > 0


def compare(got, exp):
    """(ok, detail). Compares the program's output, from its first byte to the end marker."""
    end = len(exp)
    g = got[:end]
    if g == exp:
        return True, "%d bytes identical" % end
    i = next((k for k in range(min(len(g), len(exp))) if g[k] != exp[k]), min(len(g), len(exp)))
    line = exp[:i].count(b"\n") + 1
    return False, "differs at byte %d (line %d): board %r, model %r" % (
        i, line, g[max(0, i - 20):i + 20], exp[max(0, i - 20):i + 20])
